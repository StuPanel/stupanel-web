"use client";
/**
 * Packages on a studio website. A studio often sells one package in several versions —
 * "Bronze (only photo)", "Bronze (1 day)", "Bronze (2 days)", "Silver Lite (1 day)" — so the versions of one
 * package share a card: a switch on top picks Photo only / 1 day / 2 days for every card at once, and a card
 * with a Lite version gets its own Standard / Lite toggle. A compare table sits under the cards.
 * Packages that are not versions of another one simply get a card of their own.
 */
import { useEffect, useMemo, useRef, useState } from "react";
import { money, type SitePackage } from "./site-view";

const VERSION = /\s*\((?:only\s*photo|photo\s*only|\d+\s*days?)\)\s*/gi;
export const familyOf = (name: string) => name.replace(VERSION, " ").replace(/\blite\b/i, " ").replace(/\s{2,}/g, " ").trim() || name;
const isLite = (name: string) => /\blite\b/i.test(name);
const versionOf = (p: SitePackage) => (p.photoOnly ? "photo" : `${p.days && p.days > 1 ? p.days : 1}d`);
const versionName = (v: string) => (v === "photo" ? "Photo only" : v === "1d" ? "1 day" : `${parseInt(v, 10)} days`);
const order = (v: string) => (v === "photo" ? 0 : parseInt(v, 10));

type Family = { name: string; list: SitePackage[] };

/** The price, counting to its new value when the version changes. */
function Price({ value, currency }: { value: number; currency: string }) {
  const [shown, setShown] = useState(value);
  const from = useRef(value);
  useEffect(() => {
    const start = from.current;
    from.current = value;
    if (start === value || (typeof window !== "undefined" && window.matchMedia("(prefers-reduced-motion: reduce)").matches)) { setShown(value); return; }
    let raf = 0; const t0 = performance.now();
    const step = (t: number) => {
      const k = Math.min(1, (t - t0) / 450); const e = 1 - Math.pow(1 - k, 3);
      setShown(Math.round(start + (value - start) * e));
      if (k < 1) raf = requestAnimationFrame(step);
    };
    raf = requestAnimationFrame(step);
    return () => cancelAnimationFrame(raf);
  }, [value]);
  return <>{money(shown, currency)}</>;
}

/** The "what you get" lines of one package. */
function linesOf(p: SitePackage): string[] {
  if (p.days === undefined) return p.lines; // an older server: the short lines it sent
  const out: string[] = [];
  if (p.days > 1) out.push(p.hours ? `${p.days} days · ${p.hours} hours each` : `${p.days} days of coverage`);
  else if (p.hours) out.push(`${p.hours} hours of coverage`);
  const note = p.note ?? "";
  if (/photo/i.test(note)) out.push(note);
  else if (p.photos) out.push(`${p.photos} edited photos`);
  const vid = [p.trailers ? `${p.trailers} trailer${p.trailers > 1 ? "s" : ""}` : "", p.films ? `${p.films} full film${p.films > 1 ? "s" : ""}` : ""].filter(Boolean).join(" · ");
  if (vid) out.push(vid);
  if (note && !/photo/i.test(note)) out.push(note);
  for (const x of p.extras ?? []) out.push(x);
  if (p.delivery) out.push(`Delivered ${p.delivery.startsWith("Online") ? p.delivery.replace(/^Online/, "online") : `on ${p.delivery}`}`);
  return out;
}

export function PackageBrowser({ packages, ask, heading }: { packages: SitePackage[]; ask: (p: SitePackage) => React.ReactNode; heading?: "h2" | "h3" }) {
  const groups = useMemo(() => Array.from(new Set(packages.map(p => p.group))), [packages]);
  const [tab, setTab] = useState(0);
  const group = groups[Math.min(tab, groups.length - 1)];
  const inGroup = useMemo(() => packages.filter(p => p.group === group), [packages, group]);

  // Families: the versions of one package, in the order the studio sorted them.
  const families = useMemo(() => {
    const m = new Map<string, Family>();
    for (const p of inGroup) { const k = familyOf(p.name).toLowerCase(); if (!m.has(k)) m.set(k, { name: familyOf(p.name), list: [] }); m.get(k)!.list.push(p); }
    return Array.from(m.values());
  }, [inGroup]);
  const versions = useMemo(() => Array.from(new Set(inGroup.map(versionOf))).sort((a, b) => order(a) - order(b)), [inGroup]);
  const grouped = families.some(f => f.list.length > 1);
  const [ver, setVer] = useState<string>("");
  const v = versions.includes(ver) ? ver : versions.includes("1d") ? "1d" : versions[0];
  const [lite, setLite] = useState<Record<string, boolean>>({});

  const cards = grouped
    ? families.flatMap(f => {
        const here = f.list.filter(p => versionOf(p) === v);
        if (!here.length) return [];
        const hasBoth = here.some(p => isLite(p.name)) && here.some(p => !isLite(p.name));
        const wantLite = hasBoth ? !!lite[f.name] : here.every(p => isLite(p.name));
        const pick = here.find(p => isLite(p.name) === wantLite) ?? here[0];
        return [{ key: f.name, title: f.name, p: pick, hasBoth, onLite: wantLite }];
      })
    : inGroup.map(p => ({ key: p.id, title: p.name, p, hasBoth: false, onLite: false }));

  const H = heading ?? "h2";
  const rows: [string, (p: SitePackage) => string][] = [
    ["Price", p => money(p.price, p.currency)],
    ["Team", p => p.team || "—"],
    ["Coverage", p => (p.days && p.days > 1 ? `${p.days} days${p.hours ? `, ${p.hours} h each` : ""}` : p.hours ? `${p.hours} hours` : "—")],
    ["Edited photos", p => (p.note && /photo/i.test(p.note) ? p.note.replace(/\s*edited photos?/i, "") : p.photos ? String(p.photos) : "—")],
    ["Films", p => [p.trailers ? `${p.trailers} trailer${p.trailers > 1 ? "s" : ""}` : "", p.films ? `${p.films} full` : ""].filter(Boolean).join(" + ") || "—"],
    ["Also", p => (p.extras ?? []).join(", ") || "—"],
    ["Delivery", p => p.delivery || "—"],
  ];
  const canCompare = cards.length > 1 && cards[0].p.days !== undefined;

  return (
    <div className="pkb">
      {groups.length > 1 && (
        <div className="cap" style={{ display: "flex", justifyContent: "center", flexWrap: "wrap", margin: "30px 0 4px" }}>
          {groups.map((g, i) => <button key={g} type="button" className="tab cap" onClick={() => { setTab(i); setVer(""); }} aria-pressed={i === tab}>{g}</button>)}
        </div>
      )}
      {grouped && versions.length > 1 && (
        <div className="pkv" role="group" aria-label="Version">
          {versions.map(x => <button key={x} type="button" aria-pressed={x === v} onClick={() => setVer(x)}>{versionName(x)}</button>)}
        </div>
      )}
      <div className="pkg">
        {cards.map((c, i) => (
          <div key={`${group}-${c.key}`} className="pk pkc" style={{ animationName: `sgpk${i % 3}`, animationDelay: `${0.1 + i * 0.08}s` }}>
            <H className="pf" style={{ margin: 0, fontSize: 28, fontWeight: 400 }}>{c.title}</H>
            {c.hasBoth && (
              <div className="pkl" role="group" aria-label={`${c.title}: standard or lite`}>
                <button type="button" aria-pressed={!c.onLite} onClick={() => setLite(s => ({ ...s, [c.key]: false }))}>Standard</button>
                <button type="button" aria-pressed={c.onLite} onClick={() => setLite(s => ({ ...s, [c.key]: true }))}>Lite</button>
              </div>
            )}
            <div className="pf" style={{ fontSize: 26, color: "var(--mut)", margin: "10px 0 4px", fontVariantNumeric: "tabular-nums" }} aria-live="polite"><Price value={c.p.price} currency={c.p.currency} /></div>
            {grouped && versions.length > 1 && <div style={{ fontSize: 12, color: "var(--mut)", marginBottom: 6 }}>{versionName(v)}</div>}
            {c.p.team && <div className="cap" style={{ fontSize: 10, margin: "8px 0 18px" }}>{c.p.team}</div>}
            <ul className="pkli">{linesOf(c.p).map((l, k) => <li key={k}>{l}</li>)}</ul>
            <div style={{ marginTop: "auto", paddingTop: 22 }}>{ask(c.p)}</div>
          </div>
        ))}
      </div>
      {canCompare && (
        <details className="pkt rv">
          <summary className="cap">Compare packages</summary>
          <div className="pktw">
            <table>
              <thead><tr><th scope="col"><span className="sr">Detail</span></th>{cards.map(c => <th key={c.key} scope="col">{c.title}{c.onLite ? " Lite" : ""}</th>)}</tr></thead>
              <tbody>{rows.map(([label, f]) => <tr key={label}><th scope="row">{label}</th>{cards.map(c => <td key={c.key}>{f(c.p)}</td>)}</tr>)}</tbody>
            </table>
          </div>
        </details>
      )}
    </div>
  );
}
